#!/usr/bin/env node
// Builds public/design/nwebos-icons.svg from scripts/nwebos-icons.json (16x16 pixel grids, our own art from
// mockups/nwebos/src/art.py). One <path> per colour, horizontal runs merged, so the sprite stays ~6 KB.
// Run: node scripts/build-nwebos-icons.mjs   (also checked by scripts/nwebos-unit.mjs: the committed sprite must match)
import fs from "node:fs";
const ROOT = new URL("..", import.meta.url);
export function buildSprite({ P, ICONS }) {
  const out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">', "<!-- NwebOS pixel icons (own art, mockups/nwebos/src/art.py). Generated by scripts/build-nwebos-icons.mjs; one path per colour, runs merged. -->"];
  for (const [k, rows] of Object.entries(ICONS)) {
    if (!rows.length) continue;
    const by = new Map();
    rows.forEach((row, y) => {
      row = row.slice(0, 16);
      for (let x = 0; x < row.length; ) {
        const c = row[x];
        if (!P[c]) { x++; continue; }
        const s = x; while (x < row.length && row[x] === c) x++;
        if (!by.has(P[c])) by.set(P[c], []);
        by.get(P[c]).push(`M${s} ${y}h${x - s}v1h-${x - s}z`);
      }
    });
    out.push(`<symbol id="i-${k}" viewBox="0 0 16 16">${[...by].map(([col, d]) => `<path fill="${col}" d="${d.join("")}"/>`).join("")}</symbol>`);
  }
  out.push("</svg>");
  return out.join("\n") + "\n";
}
if ((process.argv[1] || "").endsWith("build-nwebos-icons.mjs")) {
  const src = JSON.parse(fs.readFileSync(new URL("scripts/nwebos-icons.json", ROOT), "utf8"));
  fs.writeFileSync(new URL("public/design/nwebos-icons.svg", ROOT), buildSprite(src));
  console.log("nwebos-icons.svg written");
}
