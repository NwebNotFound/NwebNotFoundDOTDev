// Build-time EPUB 3 writer for the Creative Hub writing section
// (docs/creative-hub-plan.md §8 "Export", §9 phase 3c).
//
// Deliberately dependency-free: a small ZIP writer (method "stored", CRC32, `mimetype` first and
// uncompressed), the EPUB 3 package document, the navigation document, one XHTML file per chapter and
// a minimal stylesheet. `scripts/build-content.mjs` calls this once per story chapter and once per
// series and writes the result to `public/downloads/` (generated at build time, not committed).
//
// Everything here is pure (no `fs`, no clock, no randomness): the same input always produces the
// same bytes, so a rebuild without a content change does not change a single file.
//
// Rules (plan §8 "Export", Nils' decisions):
//   - one EPUB per published story chapter and one per series (all non-archived chapters in order),
//   - blog posts and reviews get no export at all,
//   - the rights line is part of the export and of the page,
//   - the identifier is a stable UUID derived from the slug,
//   - a cover is only embedded when there is one,
//   - no PDF generation: the print view of the reader page is the "save as PDF" path.
import { escapeHtml } from "./markdown.js";
import { xmlEscape } from "./feed.js";

export const EPUB_MEDIA_TYPE = "application/epub+zip";
export const EPUB_AUTHOR = "Nils";
/** Download URLs: one per chapter, one per series. Generated by the build, served as a static asset. */
export const epubPath = (slug) => `/downloads/story-${slug}.epub`;
export const seriesEpubPath = (slug) => `/downloads/series-${slug}.epub`;
export const DOWNLOAD_DIR = "public/downloads";

/** Media type of an embedded image, by file extension. */
export function imageMediaType(name) {
  const ext = String(name).toLowerCase().split(".").pop();
  return { png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", gif: "image/gif", webp: "image/webp", svg: "image/svg+xml" }[ext] || "application/octet-stream";
}

/* ---- ZIP (stored, no compression) -------------------------------------------------------------- */

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[i] = c >>> 0;
  }
  return table;
})();

/** CRC-32 of a byte array (the value a ZIP reader checks per entry). */
export function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

const bytesOf = (data) => (typeof data === "string" ? new TextEncoder().encode(data) : data instanceof Uint8Array ? data : new Uint8Array(data));
// Fixed DOS timestamp (1980-01-01 00:00:00): a rebuild must not change a single byte.
const DOS_TIME = 0;
const DOS_DATE = 0x0021;

/**
 * A ZIP archive with `method 0` (stored) entries — enough for an EPUB, no dependency, no compression.
 * The first entry is written as the local file header plus data with no extra field, which is what
 * the EPUB specification demands for `mimetype`.
 */
export function zipStore(entries) {
  const parts = [];
  const central = [];
  let offset = 0;

  const u16 = (n) => [n & 0xff, (n >>> 8) & 0xff];
  const u32 = (n) => [n & 0xff, (n >>> 8) & 0xff, (n >>> 16) & 0xff, (n >>> 24) & 0xff];

  for (const entry of entries) {
    const name = bytesOf(entry.name);
    const data = bytesOf(entry.data);
    const crc = crc32(data);
    const header = new Uint8Array([
      ...u32(0x04034b50),
      ...u16(20), // version needed
      ...u16(0), // flags
      ...u16(0), // method: stored
      ...u16(DOS_TIME),
      ...u16(DOS_DATE),
      ...u32(crc),
      ...u32(data.length),
      ...u32(data.length),
      ...u16(name.length),
      ...u16(0), // extra field length
    ]);
    parts.push(header, name, data);
    central.push(
      new Uint8Array([
        ...u32(0x02014b50),
        ...u16(20), // version made by
        ...u16(20), // version needed
        ...u16(0),
        ...u16(0),
        ...u16(DOS_TIME),
        ...u16(DOS_DATE),
        ...u32(crc),
        ...u32(data.length),
        ...u32(data.length),
        ...u16(name.length),
        ...u16(0), // extra
        ...u16(0), // comment
        ...u16(0), // disk number
        ...u16(0), // internal attributes
        ...u32(0), // external attributes
        ...u32(offset),
      ]),
      name,
    );
    offset += header.length + name.length + data.length;
  }

  const centralSize = central.reduce((sum, part) => sum + part.length, 0);
  const eocd = new Uint8Array([
    ...u32(0x06054b50),
    ...u16(0),
    ...u16(0),
    ...u16(entries.length),
    ...u16(entries.length),
    ...u32(centralSize),
    ...u32(offset),
    ...u16(0),
  ]);

  const total = offset + centralSize + eocd.length;
  const out = new Uint8Array(total);
  let at = 0;
  for (const part of parts) {
    out.set(part, at);
    at += part.length;
  }
  for (const part of central) {
    out.set(part, at);
    at += part.length;
  }
  out.set(eocd, at);
  return out;
}

/* ---- XHTML ------------------------------------------------------------------------------------ */

// The Markdown renderer emits HTML5 (void elements without a slash). XHTML needs them closed.
const VOID_ELEMENTS = ["area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"];

/** Close void elements so the fragment is well-formed XHTML. Idempotent for already closed tags. */
export function htmlToXhtml(html) {
  let out = String(html ?? "");
  for (const tag of VOID_ELEMENTS) {
    out = out.replace(new RegExp(`<${tag}\\b([^>]*?)\\s*/?>`, "gi"), (m, attrs) => `<${tag}${attrs.replace(/\s+$/, "")}/>`);
  }
  return out;
}

/**
 * Rewrite a rendered chapter for an EPUB: internal absolute links become absolute URLs on the site
 * (a reader has no origin), embedded images become relative references, images without a local file
 * are dropped.
 * `images` maps `/content-assets/x.png` → `{ href: "images/x.png" }`.
 */
export function rewriteForEpub(html, { site, images = {} } = {}) {
  let out = String(html ?? "");
  out = out.replace(/<img\b[^>]*>/gi, (tag) => {
    const src = /src="([^"]*)"/i.exec(tag)?.[1] || "";
    const image = images[src];
    if (!image) return ""; // no local file: a reference inside the EPUB would be broken
    return tag.replace(/src="[^"]*"/i, `src="${image.href}"`);
  });
  out = out.replace(/href="\/([^"]*)"/gi, (m, rest) => `href="https://${site}/${rest}"`);
  return htmlToXhtml(out);
}

/** One XHTML document. `body` is already XHTML (see `rewriteForEpub`). */
export function xhtmlDocument({ title, lang, body, css = "style.css" }) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="${xmlEscape(lang)}" lang="${xmlEscape(lang)}">
<head>
<meta charset="utf-8"/>
<title>${xmlEscape(title)}</title>
<link rel="stylesheet" type="text/css" href="${xmlEscape(css)}"/>
</head>
<body>
${body}
</body>
</html>
`;
}

/** Minimal, readable stylesheet: no remote font, serif-free, page breaks before every chapter. */
export const EPUB_CSS = `html { font-family: sans-serif; }
body { margin: 0 5%; line-height: 1.5; }
h1, h2, h3 { line-height: 1.25; }
h2 { page-break-before: always; break-before: page; }
img { max-width: 100%; height: auto; }
blockquote { margin: 1em 0; padding-left: 1em; border-left: 3px solid #999; }
pre { white-space: pre-wrap; }
.epub-rights { margin-top: 2em; border-top: 1px solid #999; padding-top: 0.5em; font-size: 0.85em; }
.epub-meta { color: #555; font-size: 0.9em; }
`;

/* ---- identifiers and metadata ------------------------------------------------------------------ */

const hash = (text, seed) => {
  let h = seed >>> 0;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
};

const hex = (value, width) => value.toString(16).padStart(width, "0");

/** A stable UUID (RFC 4122 shape, version 4) derived from a slug: the same story keeps its id. */
export function epubIdentifier(seed) {
  const a = hex(hash(String(seed), 0x811c9dc5), 8);
  const b = hex(hash(`${seed}#b`, 0x01000193), 8);
  const c = hex(hash(`${seed}#c`, 0xdeadbeef), 8);
  const variant = "89ab"[hash(`${seed}#v`, 0x9e3779b9) % 4];
  return `${a}-${b.slice(0, 4)}-4${b.slice(4, 7)}-${variant}${c.slice(0, 3)}-${c.slice(3, 8)}${hex(hash(`${seed}#d`, 0x85ebca6b), 8).slice(0, 7)}`;
}

/** `2026-11-04` → `2026-11-04T00:00:00Z` (dcterms:modified, deterministic). */
export const modifiedStamp = (date) => `${date}T00:00:00Z`;

/* ---- the EPUB --------------------------------------------------------------------------------- */

function titlePageXhtml({ title, seriesTitle, chapter, lang, date, rights, site }) {
  const meta = [seriesTitle ? xmlEscape(seriesTitle) : "", chapter ? `Kapitel ${chapter}` : "", date].filter(Boolean).join(" · ");
  return xhtmlDocument({
    title,
    lang,
    body: `<h1>${xmlEscape(title)}</h1>
<p class="epub-meta">${meta}</p>
<p class="epub-meta">${xmlEscape(EPUB_AUTHOR)} · ${xmlEscape(site)}</p>
<p class="epub-rights">${xmlEscape(rights)}</p>`,
  });
}

function navXhtml({ title, lang, chapters }) {
  const items = chapters.map((c) => `<li><a href="${xmlEscape(c.file)}">${xmlEscape(c.title)}</a></li>`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="${xmlEscape(lang)}" lang="${xmlEscape(lang)}">
<head>
<meta charset="utf-8"/>
<title>${xmlEscape(title)}</title>
</head>
<body>
<nav epub:type="toc" id="toc">
<h1>${xmlEscape(title)}</h1>
<ol>
${items}
</ol>
</nav>
</body>
</html>
`;
}

function packageOpf({ title, lang, identifier, date, rights, chapters, images, cover, hasNavInSpine = true }) {
  const manifest = [
    `<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>`,
    `<item id="css" href="style.css" media-type="text/css"/>`,
    `<item id="titlepage" href="titlepage.xhtml" media-type="application/xhtml+xml"/>`,
    ...chapters.map((c) => `<item id="${xmlEscape(c.id)}" href="${xmlEscape(c.file)}" media-type="application/xhtml+xml"/>`),
    ...images.map((img) => `<item id="${xmlEscape(img.id)}" href="${xmlEscape(img.href)}" media-type="${xmlEscape(img.mediaType)}"${img.cover ? ' properties="cover-image"' : ""}/>`),
    ...(cover ? [`<item id="cover" href="cover.xhtml" media-type="application/xhtml+xml"/>`] : []),
  ].join("\n    ");
  const spine = [
    ...(cover ? [`<itemref idref="cover"/>`] : []),
    `<itemref idref="titlepage"/>`,
    ...(hasNavInSpine ? [`<itemref idref="nav"/>`] : []),
    ...chapters.map((c) => `<itemref idref="${xmlEscape(c.id)}"/>`),
  ].join("\n    ");
  return `<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="pub-id" xml:lang="${xmlEscape(lang)}">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="pub-id">urn:uuid:${xmlEscape(identifier)}</dc:identifier>
    <dc:title>${xmlEscape(title)}</dc:title>
    <dc:language>${xmlEscape(lang)}</dc:language>
    <dc:creator id="author">${xmlEscape(EPUB_AUTHOR)}</dc:creator>
    <dc:rights>${xmlEscape(rights)}</dc:rights>
    <dc:date>${xmlEscape(date)}</dc:date>
    <meta property="dcterms:modified">${xmlEscape(modifiedStamp(date))}</meta>
    ${cover ? `<meta name="cover" content="${xmlEscape(cover.id)}"/>` : ""}
  </metadata>
  <manifest>
    ${manifest}
  </manifest>
  <spine>
    ${spine}
  </spine>
</package>
`;
}

const CONTAINER_XML = `<?xml version="1.0" encoding="utf-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
`;

/**
 * Build one EPUB 3 file.
 *
 * `chapters`: `[{ slug, title, html }]` in reading order (already Markdown-rendered).
 * `images`: `{ "/content-assets/x.png": { bytes, mediaType } }` — resolved by the caller from disk.
 * `cover`: optional `{ bytes, mediaType, name }`.
 */
export function buildEpub({ title, lang, identifier, date, rights, chapters, images = {}, cover = null, site = "nwebnotfound.dev", seriesTitle = null }) {
  if (!chapters.length) throw new Error("an EPUB needs at least one chapter");
  // dc:language and dcterms:modified are mandatory in EPUB 3 — refuse to write an invalid file.
  if (!lang) throw new Error("an EPUB needs a language");
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(date))) throw new Error(`an EPUB needs a YYYY-MM-DD date (got "${date}")`);

  const embedded = [];
  const imageMap = {};
  let imageIndex = 0;
  for (const [path, image] of Object.entries(images)) {
    const name = String(path).split("/").pop();
    imageIndex += 1;
    const id = `img${imageIndex}`;
    const href = `images/${name}`;
    imageMap[path] = { href };
    embedded.push({ id, href, name, bytes: image.bytes, mediaType: image.mediaType || imageMediaType(name) });
  }
  // A cover is only embedded when there is one; it is a normal manifest item with `cover-image`.
  let coverImage = null;
  if (cover) {
    const ext = String(cover.name).split(".").pop().toLowerCase();
    coverImage = { id: "cover-image", href: `images/cover.${ext}`, name: `cover.${ext}`, bytes: cover.bytes, mediaType: cover.mediaType || imageMediaType(cover.name), cover: true };
    embedded.push(coverImage);
  }

  const files = chapters.map((chapter, index) => ({
    id: `ch${index + 1}`,
    file: `chapter-${index + 1}.xhtml`,
    title: chapter.title,
    xhtml: xhtmlDocument({ title: chapter.title, lang, body: rewriteForEpub(chapter.html, { site, images: imageMap }) }),
  }));

  const entries = [{ name: "mimetype", data: EPUB_MEDIA_TYPE }];
  entries.push({ name: "META-INF/container.xml", data: CONTAINER_XML });
  entries.push({ name: "OEBPS/content.opf", data: packageOpf({ title, lang, identifier, date, rights, chapters: files, images: embedded, cover: coverImage }) });
  entries.push({ name: "OEBPS/nav.xhtml", data: navXhtml({ title, lang, chapters: files }) });
  entries.push({ name: "OEBPS/titlepage.xhtml", data: titlePageXhtml({ title, seriesTitle, chapter: chapters.length === 1 ? chapters[0].chapter : null, lang, date, rights, site }) });
  entries.push({ name: "OEBPS/style.css", data: EPUB_CSS });
  for (const file of files) entries.push({ name: `OEBPS/${file.file}`, data: file.xhtml });
  for (const image of embedded) entries.push({ name: `OEBPS/${image.href}`, data: image.bytes });
  if (coverImage) {
    entries.push({
      name: "OEBPS/cover.xhtml",
      data: xhtmlDocument({ title, lang, body: `<div><img src="${coverImage.href}" alt="${escapeHtml(title)}"/></div>` }),
    });
  }

  return zipStore(entries);
}

/**
 * Build every export of a content index: one EPUB per published story chapter, one per series with
 * published chapters. Blog posts (and later reviews) get nothing — Nils' decision (plan §0).
 * `readImage(path)` resolves a `/content-assets/…` path to `{ bytes, mediaType }` or `null`.
 */
export function buildEpubs({ writing = [], series = [], site = "nwebnotfound.dev", rights, readImage = () => null }) {
  const published = writing.filter((w) => w.kind === "story" && !w.draft && !w.archived && w.series);
  const out = [];

  const imagesFor = (chapters) => {
    const wanted = {};
    for (const chapter of chapters) {
      for (const m of String(chapter.html || "").matchAll(/src="(\/content-assets\/[^"]+)"/g)) {
        if (wanted[m[1]]) continue;
        const image = readImage(m[1]);
        if (image) wanted[m[1]] = image;
      }
    }
    return wanted;
  };
  const coverFor = (chapters) => {
    for (const chapter of chapters) {
      if (!chapter.cover) continue;
      const image = readImage(chapter.cover);
      if (image) return { ...image, name: String(chapter.cover).split("/").pop() };
    }
    return null;
  };
  const titleFor = (chapters) => {
    const first = chapters[0];
    return { lang: first.lang, date: chapters.map((c) => c.date).sort().at(-1) };
  };

  for (const item of published) {
    const chapters = [{ slug: item.slug, title: item.title, chapter: item.chapter, cover: item.cover, lang: item.lang, date: item.date, html: item.html }];
    const { lang, date } = titleFor(chapters);
    out.push({
      path: epubPath(item.slug),
      slug: item.slug,
      kind: "chapter",
      bytes: buildEpub({
        title: item.title,
        seriesTitle: item.seriesTitle || item.series,
        lang,
        date,
        identifier: epubIdentifier(`chapter:${item.slug}`),
        rights: rights(lang),
        chapters,
        images: imagesFor(chapters),
        cover: coverFor(chapters),
        site,
      }),
    });
  }

  for (const s of series) {
    const chapters = published.filter((c) => c.series === s.slug).sort((a, b) => a.chapter - b.chapter || a.slug.localeCompare(b.slug));
    if (!chapters.length) continue;
    const { lang, date } = titleFor(chapters);
    out.push({
      path: seriesEpubPath(s.slug),
      slug: s.slug,
      kind: "series",
      bytes: buildEpub({
        title: s.title || s.slug,
        lang,
        date,
        identifier: epubIdentifier(`series:${s.slug}`),
        rights: rights(lang),
        chapters: chapters.map((c) => ({ slug: c.slug, title: c.title, chapter: c.chapter, html: c.html })),
        images: imagesFor(chapters),
        cover: coverFor(chapters),
        site,
      }),
    });
  }

  return out.sort((a, b) => a.path.localeCompare(b.path));
}
